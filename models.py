def update_conversation(conversation_id, title=None, is_pinned=None, model=None):
    """Updates conversation metadata."""
    conn = get_connection()
    is_ora = is_oracle()
    cursor = conn.cursor()
    try:
        if is_ora:
            if title is not None:
                cursor.execute("UPDATE conversations SET title = :1, updated_at = CURRENT_TIMESTAMP WHERE conversation_id = :2", (safe_str(title)[:290], conversation_id))
            if is_pinned is not None:
                cursor.execute("UPDATE conversations SET is_pinned = :1, updated_at = CURRENT_TIMESTAMP WHERE conversation_id = :2", (1 if is_pinned else 0, conversation_id))
            if model is not None:
                cursor.execute("UPDATE conversations SET model = :1, updated_at = CURRENT_TIMESTAMP WHERE conversation_id = :2", (model, conversation_id))
        else:
            if title is not None:
                cursor.execute("UPDATE conversations SET title = ?, updated_at = CURRENT_TIMESTAMP WHERE conversation_id = ?", (title, conversation_id))
            if is_pinned is not None:
                cursor.execute("UPDATE conversations SET is_pinned = ?, updated_at = CURRENT_TIMESTAMP WHERE conversation_id = ?", (1 if is_pinned else 0, conversation_id))
            if model is not None:
                cursor.execute("UPDATE conversations SET model = ?, updated_at = CURRENT_TIMESTAMP WHERE conversation_id = ?", (model, conversation_id))
        conn.commit()
    finally:
        cursor.close()
        conn.close()


