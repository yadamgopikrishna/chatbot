def get_user_by_email(email):
    """Fetches user record by email."""
    conn = get_connection()
    is_ora = is_oracle()
    cursor = conn.cursor()
    try:
        if is_ora:
            cursor.execute("SELECT column_name FROM user_tab_columns WHERE table_name = 'USERS'")
            cols = [row[0].upper() for row in cursor.fetchall()]
            
            has_lang = "PREFERRED_LANG" in cols
            has_theme = "THEME" in cols
            
            query = "SELECT user_id, name, email, password, created_date"
            if has_lang:
                query += ", preferred_lang"
            if has_theme:
                query += ", theme"
            query += " FROM users WHERE email = :1"
            
            cursor.execute(query, (email,))
            row = cursor.fetchone()
            if row:
                user_dict = {
                    "user_id": row[0],
                    "name": row[1],
                    "email": row[2],
                    "password": row[3],
                    "created_date": str(row[4]),
                    "preferred_lang": "auto",
                    "theme": "dark"
                }
                idx = 5
                if has_lang and len(row) > idx:
                    user_dict["preferred_lang"] = row[idx] or "auto"
                    idx += 1
                if has_theme and len(row) > idx:
                    user_dict["theme"] = row[idx] or "dark"
                return user_dict
        else:
            cursor.execute("SELECT * FROM users WHERE email = ?", (email,))
            row = cursor.fetchone()
            if row:
                return dict(row)
        return None
    finally:
        cursor.close()
        conn.close()


