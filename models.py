def save_document_chunks(doc_id, chunks):
    """Saves a batch of chunks for a document."""
    conn = get_connection()
    is_ora = is_oracle()
    cursor = conn.cursor()
    try:
        for i, chunk in enumerate(chunks):
            chunk_id = str(uuid.uuid4())
            page_num = chunk.get("page", 1)
            content = safe_str(chunk.get("text", ""))
            meta_json = json.dumps(chunk.get("metadata", {}), ensure_ascii=False)

            if is_ora:
                cursor.execute(
                    "INSERT INTO document_chunks (chunk_id, doc_id, chunk_index, page_number, content, metadata_json) "
                    "VALUES (:1, :2, :3, :4, :5, :6)",
                    (chunk_id, doc_id, i, page_num, content, meta_json)
                )
            else:
                cursor.execute(
                    "INSERT INTO document_chunks (chunk_id, doc_id, chunk_index, page_number, content, metadata_json) "
                    "VALUES (?, ?, ?, ?, ?, ?)",
                    (chunk_id, doc_id, i, page_num, content, meta_json)
                )
        conn.commit()
    finally:
        cursor.close()
        conn.close()


