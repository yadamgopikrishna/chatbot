def save_message(conversation_id, sender, content, attachments=None, citations=None, chart_data=None, forensics=None):
    """Saves a message to the database."""
    msg_id = str(uuid.uuid4())
    att_json = json.dumps(attachments, ensure_ascii=False) if attachments else None
    cit_json = json.dumps(citations, ensure_ascii=False) if citations else None
    chart_json = json.dumps(chart_data, ensure_ascii=False) if chart_data else None
    forensics_json = json.dumps(forensics, ensure_ascii=False) if forensics else None

    conn = get_connection()
    is_ora = is_oracle()
    cursor = conn.cursor()
    try:
        safe_content = safe_str(content)
        if is_ora:
            cursor.execute(
                "INSERT INTO messages (message_id, conversation_id, sender, content, attachments_json, citations_json, chart_data_json, forensics_json, created_at) "
                "VALUES (:1, :2, :3, :4, :5, :6, :7, :8, CURRENT_TIMESTAMP)",
                (msg_id, conversation_id, sender, safe_content, att_json, cit_json, chart_json, forensics_json)
            )
            cursor.execute("UPDATE conversations SET updated_at = CURRENT_TIMESTAMP WHERE conversation_id = :1", (conversation_id,))
        else:
            cursor.execute(
                "INSERT INTO messages (message_id, conversation_id, sender, content, attachments_json, citations_json, chart_data_json, forensics_json) "
                "VALUES (?, ?, ?, ?, ?, ?, ?, ?)",
                (msg_id, conversation_id, sender, safe_content, att_json, cit_json, chart_json, forensics_json)
            )
            cursor.execute("UPDATE conversations SET updated_at = CURRENT_TIMESTAMP WHERE conversation_id = ?", (conversation_id,))
        conn.commit()
        return msg_id
    except Exception as e:
        logger.warning("save_message note: %s", e)
        return msg_id
    finally:
        cursor.close()
        conn.close()


def get_conversation_messages(conversation_id):
    """Retrieves all messages for a given conversation."""
    conn = get_connection()
    is_ora = is_oracle()
    cursor = conn.cursor()
    try:
        if is_ora:
            cursor.execute(
                "SELECT message_id, conversation_id, sender, content, attachments_json, citations_json, chart_data_json, forensics_json, created_at "
                "FROM messages WHERE conversation_id = :1 ORDER BY created_at ASC",
                (conversation_id,)
            )
            rows = cursor.fetchall()
            result = []
            for r in rows:
                content_str = r[3].read() if hasattr(r[3], 'read') else str(r[3])
                att_str = r[4].read() if hasattr(r[4], 'read') else r[4]
                cit_str = r[5].read() if hasattr(r[5], 'read') else r[5]
                chart_str = r[6].read() if hasattr(r[6], 'read') else r[6]
                for_str = r[7].read() if hasattr(r[7], 'read') else r[7]
                result.append({
                    "message_id": r[0],
                    "conversation_id": r[1],
                    "sender": r[2],
                    "content": content_str,
                    "attachments": json.loads(att_str) if att_str else [],
                    "citations": json.loads(cit_str) if cit_str else [],
                    "chart_data": json.loads(chart_str) if chart_str else None,
                    "forensics": json.loads(for_str) if for_str else None,
                    "created_at": str(r[8])
                })
            return result
        else:
            cursor.execute("SELECT * FROM messages WHERE conversation_id = ? ORDER BY created_at ASC", (conversation_id,))
            rows = cursor.fetchall()
            result = []
            for r in rows:
                item = dict(r)
                item["attachments"] = json.loads(item["attachments_json"]) if item.get("attachments_json") else []
                item["citations"] = json.loads(item["citations_json"]) if item.get("citations_json") else []
                item["chart_data"] = json.loads(item["chart_data_json"]) if item.get("chart_data_json") else None
                item["forensics"] = json.loads(item["forensics_json"]) if item.get("forensics_json") else None
                result.append(item)
            return result
    finally:
        cursor.close()
        conn.close()


