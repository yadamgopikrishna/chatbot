logger = logging.getLogger(__name__)

def safe_str(val):
    """Ensures val is clean string without encoding anomalies."""
    if val is None:
        return None
    if isinstance(val, str):
        return val
    return str(val)


def init_db():
    """Initializes and migrates database tables in Oracle XE or SQLite."""
    conn = get_connection()
    is_ora = is_oracle()
    cursor = conn.cursor()

    try:
        if is_ora:
            _init_oracle_tables(cursor, conn)
        else:
            _init_sqlite_tables(cursor, conn)
    except Exception as e:
        logger.error("Error during database initialization: %s", e)
    finally:
        cursor.close()
        conn.close()


def _init_oracle_tables(cursor, conn):
    """Initializes tables for Oracle Database."""
    cursor.execute("SELECT table_name FROM user_tables")
    existing_tables = {row[0].upper() for row in cursor.fetchall()}

    # 1. USERS table
    if "USERS" not in existing_tables:
        cursor.execute("""
            CREATE TABLE users (
                user_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                name VARCHAR2(150) NOT NULL,
                email VARCHAR2(150) UNIQUE NOT NULL,
                password VARCHAR2(255) NOT NULL,
                created_date DATE DEFAULT SYSDATE,
                preferred_lang VARCHAR2(20) DEFAULT 'auto',
                theme VARCHAR2(20) DEFAULT 'dark'
            )
        """)
        conn.commit()
        logger.info("Oracle table 'USERS' created")
    else:
        cursor.execute("SELECT column_name FROM user_tab_columns WHERE table_name = 'USERS'")
        existing_cols = {row[0].upper() for row in cursor.fetchall()}
        if "PREFERRED_LANG" not in existing_cols:
            try:
                cursor.execute("ALTER TABLE users ADD preferred_lang VARCHAR2(20) DEFAULT 'auto'")
                conn.commit()
            except Exception:
                pass
        if "THEME" not in existing_cols:
            try:
                cursor.execute("ALTER TABLE users ADD theme VARCHAR2(20) DEFAULT 'dark'")
                conn.commit()
            except Exception:
                pass

    # 2. CONVERSATIONS table
    if "CONVERSATIONS" not in existing_tables:
        cursor.execute("""
            CREATE TABLE conversations (
                conversation_id VARCHAR2(64) PRIMARY KEY,
                user_email VARCHAR2(150) NOT NULL,
                title VARCHAR2(300) NOT NULL,
                model VARCHAR2(100) DEFAULT 'gemini-2.5-flash',
                is_pinned NUMBER(1) DEFAULT 0,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.commit()
        logger.info("Oracle table 'CONVERSATIONS' created")

    # 3. MESSAGES table
    if "MESSAGES" not in existing_tables:
        cursor.execute("""
            CREATE TABLE messages (
                message_id VARCHAR2(64) PRIMARY KEY,
                conversation_id VARCHAR2(64) NOT NULL,
                sender VARCHAR2(20) NOT NULL,
                content CLOB NOT NULL,
                attachments_json CLOB,
                citations_json CLOB,
                chart_data_json CLOB,
                forensics_json CLOB,
                created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
                token_count NUMBER DEFAULT 0
            )
        """)
        conn.commit()
        logger.info("Oracle table 'MESSAGES' created")

    # 4. DOCUMENTS table
    if "DOCUMENTS" not in existing_tables:
        cursor.execute("""
            CREATE TABLE documents (
                doc_id VARCHAR2(64) PRIMARY KEY,
                user_email VARCHAR2(150) NOT NULL,
                conversation_id VARCHAR2(64),
                filename VARCHAR2(300) NOT NULL,
                file_type VARCHAR2(50) NOT NULL,
                file_size NUMBER NOT NULL,
                file_path VARCHAR2(500) NOT NULL,
                page_count NUMBER DEFAULT 1,
                status VARCHAR2(50) DEFAULT 'ready',
                metadata_json CLOB,
                uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
            )
        """)
        conn.commit()
        logger.info("Oracle table 'DOCUMENTS' created")

    # 5. DOCUMENT_CHUNKS table (for RAG)
    if "DOCUMENT_CHUNKS" not in existing_tables:
        cursor.execute("""
            CREATE TABLE document_chunks (
                chunk_id VARCHAR2(64) PRIMARY KEY,
                doc_id VARCHAR2(64) NOT NULL,
                chunk_index NUMBER NOT NULL,
                page_number NUMBER DEFAULT 1,
                content CLOB NOT NULL,
                metadata_json CLOB
            )
        """)
        conn.commit()
        logger.info("Oracle table 'DOCUMENT_CHUNKS' created")


def _init_sqlite_tables(cursor, conn):
    """Initializes tables for SQLite."""
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS users (
            user_id INTEGER PRIMARY KEY AUTOINCREMENT,
            name TEXT NOT NULL,
            email TEXT UNIQUE NOT NULL,
            password TEXT NOT NULL,
            created_date TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            preferred_lang TEXT DEFAULT 'auto',
            theme TEXT DEFAULT 'dark'
        )
    """)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS conversations (
            conversation_id TEXT PRIMARY KEY,
            user_email TEXT NOT NULL,
            title TEXT NOT NULL,
            model TEXT DEFAULT 'gemini-2.5-flash',
            is_pinned INTEGER DEFAULT 0,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS messages (
            message_id TEXT PRIMARY KEY,
            conversation_id TEXT NOT NULL,
            sender TEXT NOT NULL,
            content TEXT NOT NULL,
            attachments_json TEXT,
            citations_json TEXT,
            chart_data_json TEXT,
            forensics_json TEXT,
            created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
            token_count INTEGER DEFAULT 0
        )
    """)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS documents (
            doc_id TEXT PRIMARY KEY,
            user_email TEXT NOT NULL,
            conversation_id TEXT,
            filename TEXT NOT NULL,
            file_type TEXT NOT NULL,
            file_size INTEGER NOT NULL,
            file_path TEXT NOT NULL,
            page_count INTEGER DEFAULT 1,
            status TEXT DEFAULT 'ready',
            metadata_json TEXT,
            uploaded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP
        )
    """)
    cursor.execute("""
        CREATE TABLE IF NOT EXISTS document_chunks (
            chunk_id TEXT PRIMARY KEY,
            doc_id TEXT NOT NULL,
            chunk_index INTEGER NOT NULL,
            page_number INTEGER DEFAULT 1,
            content TEXT NOT NULL,
            metadata_json TEXT
        )
    """)
    conn.commit()
    logger.info("SQLite tables initialized")


